function staffLang() {
  const v = localStorage.getItem("staffLang") || "en";
  return STAFF_I18N[v] ? v : "en";
}
function t(key, ...args) {
  const dict = STAFF_I18N[staffLang()] || STAFF_I18N.en;
  let s = dict[key] ?? STAFF_I18N.en[key] ?? key;
  args.forEach((a, i) => {
    s = String(s).replace(new RegExp("\\{" + i + "\\}", "g"), a);
  });
  return s;
}
function tStatus(status) {
  const map = {
    Booked: "booked",
    Assigned: "assigned",
    Accepted: "accepted",
    "Reached Passenger": "reachedPassenger",
    "Service Started": "serviceStarted",
    Completed: "completed",
    Rejected: "rejected",
  };
  return map[status] ? t(map[status]) : status;
}
function tService(service) {
  const s = String(service || "").toLowerCase();
  if (s.includes("vehicle")) return t("vehicle");
  if (s === "porter") return t("porter");
  if (s === "wheelchair") return t("wheelchair");
  return service || "";
}
function initStaffI18n() {
  const lang = staffLang();
  document.documentElement.lang =
    lang === "hi" ? "hi" : lang === "mr" ? "mr" : "en";
  const sel = $("#staffLang");
  if (sel) {
    sel.value = lang;
    sel.setAttribute("aria-label", t("language"));
    sel.addEventListener("change", () => {
      localStorage.setItem("staffLang", sel.value);
      location.reload();
    });
  }
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key) return;
    if (el.tagName === "INPUT" || el.tagName === "TEXTAREA")
      el.setAttribute("placeholder", t(key));
    else el.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  const titleEl = $("[data-i18n-title]");
  if (titleEl) document.title = t(titleEl.getAttribute("data-i18n-title"));
}
function staffFillPager(sel, page, pages) {
  const el = $(sel);
  if (!el) return;
  el.innerHTML = !pages
    ? ""
    : `<button type="button" class="btn sm outline" data-list-page="${page - 1}" ${page <= 1 ? "disabled" : ""}>${t("prev")}</button><span>${t("pageOf", page, pages)}</span><button type="button" class="btn sm outline" data-list-page="${page + 1}" ${page >= pages ? "disabled" : ""}>${t("next")}</button>`;
}
